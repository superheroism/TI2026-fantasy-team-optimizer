import { mkdtemp, readFile, readdir, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import { spawn } from 'node:child_process';

const root = resolve('.');
const outputRoot = resolve('artifacts/p52-history');
const refs = [
  {label:'pre-p51', sha:'f1543af29f76c8338bbd01506e3d4edc5f537dfd', externalWatchdog:true},
  {label:'p51', sha:'8ee22ce5e5197213501d1e528c9d4ec4075353df', externalWatchdog:false},
  {label:'current-main', sha:'89b60573d0c176edccc40ffa4681608b5ab6ffbd', externalWatchdog:false},
];
const PRE_P51_BOARD_TIMEOUT_MS = 25_000;

async function run(command,args,options={}) {
  return await new Promise((resolvePromise,reject)=>{
    const child=spawn(command,args,{
      cwd:options.cwd||root,
      stdio:'inherit',
      env:{...process.env,...options.env},
      detached:options.detached??false,
    });
    let timedOut=false;
    let timer;
    if(options.timeoutMs){
      timer=setTimeout(()=>{
        timedOut=true;
        try{
          if(process.platform!=='win32'&&child.pid)process.kill(-child.pid,'SIGKILL');
          else child.kill('SIGKILL');
        }catch{ /* process may already have exited */ }
      },options.timeoutMs);
    }
    child.once('error',error=>{if(timer)clearTimeout(timer);reject(error);});
    child.once('exit',(code,signal)=>{
      if(timer)clearTimeout(timer);
      if(code===0)return resolvePromise({timedOut:false});
      if(timedOut)return resolvePromise({timedOut:true});
      reject(new Error(`${command} ${args.join(' ')} failed with ${signal||`exit ${code}`}`));
    });
  });
}
function metric(result, field) {
  if(field==='slotCount') return result.emblems?.length ?? 0;
  if(field==='layout') return result.comparison?.layoutCorrect ? '✓' : '✗';
  if(field==='token') return result.comparison?.tokenExact ? '✓' : '✗';
  return result.comparison?.[field] ?? '';
}
function aggregate(results){
  return {
    boards:results.length,
    exactBoards:results.filter(result=>result.comparison.exact&&!result.error).length,
    layoutCorrect:results.filter(result=>result.comparison.layoutCorrect).length,
    falseHighConfidenceErrors:results.reduce((sum,result)=>sum+(result.comparison.falseHighConfidenceErrors||0),0),
    invalidGeometryCount:results.reduce((sum,result)=>sum+(result.invalidGeometryCount||0),0),
    timeoutCount:results.reduce((sum,result)=>sum+(result.timeoutCount||0),0),
    elapsedMs:results.reduce((sum,result)=>sum+(result.elapsedMs||0),0),
  };
}
function timeoutResult(truth){
  const slots=truth.layoutId==='expanded_5'?15:9;
  return {
    sourceFile:truth.sourceFile,
    stressCase:truth.stressCase||null,
    elapsedMs:PRE_P51_BOARD_TIMEOUT_MS,
    error:'external-harness-timeout: historical OCR did not return before the compatibility watchdog',
    inferredLayout:null,
    roleColumnMethod:null,
    rowDetection:{globalRows:[],rowsByColumn:null,synthesizedRows:null},
    emblems:[],rosterEvidence:null,operationIds:null,tokensRemaining:null,
    fieldConfidence:[],reviewRequiredFields:[],ocrCallCount:0,timeoutCount:1,
    invalidGeometryCount:0,invalidCallGeometry:[],invalidEmblemGeometry:[],ocrCalls:[],
    comparison:{
      checks:[],layoutCorrect:false,statsExact:`0/${slots}`,tiersExact:`0/${slots}`,
      traitsExact:`0/${slots}`,actionsExact:'0/3',tokenExact:false,
      falseHighConfidenceErrors:0,exact:false,
    },
  };
}
function markdown(reports) {
  const lines=[
    '# P52 Historical OCR Regression Baseline',
    '',
    'Generated by the production-path six-image corpus runner before P52 algorithm changes.',
    'Pre-P51 runs use a 25-second external per-board watchdog because that implementation has no reliable bounded-call safety on these full-client images. A watchdog termination records a historical hang; it does not modify the historical OCR implementation.',
    '',
    '| Commit | Board | Layout | Slots | Stats | Tiers | Traits | Actions | Token | Invalid ROI | Timeouts | False-high-confidence | Elapsed ms |',
    '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|',
  ];
  for(const report of reports){
    for(const result of report.data.results){
      lines.push(`| ${report.label} \`${report.sha.slice(0,8)}\` | ${basename(result.sourceFile)} | ${metric(result,'layout')} | ${metric(result,'slotCount')} | ${metric(result,'statsExact')} | ${metric(result,'tiersExact')} | ${metric(result,'traitsExact')} | ${metric(result,'actionsExact')} | ${metric(result,'token')} | ${result.invalidGeometryCount} | ${result.timeoutCount} | ${result.comparison.falseHighConfidenceErrors} | ${Math.round(result.elapsedMs||0)} |`);
    }
  }
  lines.push(
    '',
    '## Aggregate',
    '',
    '| Commit | Correct layouts | Exact boards | Invalid ROI | Timeouts | False-high-confidence | Total elapsed ms |',
    '|---|---:|---:|---:|---:|---:|---:|',
  );
  for(const report of reports){
    const t=report.data.totals;
    lines.push(`| ${report.label} \`${report.sha.slice(0,8)}\` | ${t.layoutCorrect}/${t.boards} | ${t.exactBoards}/${t.boards} | ${t.invalidGeometryCount} | ${t.timeoutCount} | ${t.falseHighConfidenceErrors} | ${Math.round(t.elapsedMs||0)} |`);
  }
  lines.push(
    '',
    'This report is intentionally diagnostic: it compares historical OCR behavior under one current corpus/scorer and does not itself alter OCR semantics.',
    '',
  );
  return lines.join('\n');
}
async function loadTruth(){
  const directory=join(root,'tests/test_boards');
  const names=(await readdir(directory)).filter(name=>name.endsWith('.ground-truth.json')).sort();
  return await Promise.all(names.map(async name=>JSON.parse(await readFile(join(directory,name),'utf8'))));
}
async function makeFilteredRunner(workRoot){
  const source=await readFile(join(root,'scripts/test-ocr-corpus.mjs'),'utf8');
  const needle="const corpus = await readCorpus();\nif (corpus.length !== 6) throw new Error(`Expected six P52 ground-truth sidecars, found ${corpus.length}.`);";
  const replacement="const fullCorpus = await readCorpus();\nconst requestedBoard = process.env.P52_SINGLE_BOARD;\nconst corpus = requestedBoard ? fullCorpus.filter(row=>row.sourceFile===requestedBoard) : fullCorpus;\nif ((!requestedBoard&&corpus.length!==6)||(requestedBoard&&corpus.length!==1)) throw new Error(`Unexpected P52 corpus selection: ${corpus.length}.`);";
  if(!source.includes(needle))throw new Error('Historical compatibility runner patch point was not found.');
  const path=join(workRoot,'test-ocr-corpus-filtered.mjs');
  await writeFile(path,source.replace(needle,replacement));
  return path;
}

await mkdir(outputRoot,{recursive:true});
const truths=await loadTruth();
const workRoot=await mkdtemp(join(tmpdir(),'p52-history-'));
const filteredRunner=await makeFilteredRunner(workRoot);
const reports=[];
try{
  for(const ref of refs){
    const worktree=join(workRoot,ref.label);
    console.log(`\n=== P52 historical corpus: ${ref.label} ${ref.sha} ===`);
    await run('git',['worktree','add','--detach',worktree,ref.sha]);
    try{
      if(ref.externalWatchdog){
        const results=[];
        for(let index=0;index<truths.length;index++){
          const truth=truths[index];
          const output=join(outputRoot,`${ref.label}-${index+1}.json`);
          console.log(`--- ${truth.sourceFile} (external ${PRE_P51_BOARD_TIMEOUT_MS}ms watchdog) ---`);
          const status=await run(process.execPath,[
            filteredRunner,'--report-only',`--production-root=${worktree}`,
            `--corpus-root=${root}`,`--output=${output}`,
          ],{
            env:{P52_SINGLE_BOARD:truth.sourceFile},
            timeoutMs:PRE_P51_BOARD_TIMEOUT_MS,
            detached:process.platform!=='win32',
          });
          if(status.timedOut)results.push(timeoutResult(truth));
          else{
            const boardReport=JSON.parse(await readFile(output,'utf8'));
            results.push(boardReport.results[0]);
          }
        }
        const data={schemaVersion:1,productionRoot:worktree,corpusRoot:root,generatedAt:new Date().toISOString(),results,totals:aggregate(results)};
        await writeFile(join(outputRoot,`${ref.label}.json`),JSON.stringify(data,null,2)+'\n');
        reports.push({label:ref.label,sha:ref.sha,data});
      }else{
        const output=join(outputRoot,`${ref.label}.json`);
        await run(process.execPath,[
          'scripts/test-ocr-corpus.mjs','--report-only',`--production-root=${worktree}`,
          `--corpus-root=${root}`,`--output=${output}`,
        ]);
        reports.push({label:ref.label,sha:ref.sha,data:JSON.parse(await readFile(output,'utf8'))});
      }
    } finally {
      await run('git',['worktree','remove','--force',worktree]).catch(()=>undefined);
    }
  }
} finally {
  await rm(workRoot,{recursive:true,force:true});
}
const combined={schemaVersion:1,generatedAt:new Date().toISOString(),refs:reports};
await writeFile(join(outputRoot,'comparison.json'),JSON.stringify(combined,null,2)+'\n');
await writeFile(join(outputRoot,'P52_OCR_REGRESSION_BASELINE.md'),markdown(reports));
console.log(`\nHistorical comparison: ${join(outputRoot,'P52_OCR_REGRESSION_BASELINE.md')}`);
